type Translations = typeof translations.en;

interface I18nContextType {
  lang: Language;
  t: Translations;
  toggleLang: () => void;
  setLanguage: (lang: Language) => void;
}

const I18nContext = createContext<I18nContextType>({
  lang: "en",
  t: translations.en,
  toggleLang: () => {},
  setLanguage: () => {},
});

export const I18nProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [lang, setLang] = useState<Language>("en");

  useEffect(() => {
    const saved = localStorage.getItem("simhub_lang") as Language;
    if (saved && Object.keys(translations).includes(saved)) {
      setLang(saved);
    }
  }, []);

  const setLanguage = (newLang: Language) => {
    setLang(newLang);
    localStorage.setItem("simhub_lang", newLang);
  };

  const toggleLang = () => {
    const langs: Language[] = ["en", "hi", "bn", "ta", "te", "mr", "gu", "kn", "ml", "pa"];
    const nextIdx = (langs.indexOf(lang) + 1) % langs.length;
    setLanguage(langs[nextIdx]);
  };

  return (
    <I18nContext.Provider value={{ lang, t: translations[lang], toggleLang, setLanguage }}>
      {children}
    </I18nContext.Provider>
  );
};

export const useTranslation = () => useContext(I18nContext);
